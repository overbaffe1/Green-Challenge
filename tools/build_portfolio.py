#!/usr/bin/env python3
"""Regenerate the replay data, offline ZIP and the Green Challenge exhibit assets.

Run from the checkout with requirements-dev.txt, Pillow and DejaVu Sans installed.
Only the scripted two-hop CPU smoke test runs here, not GreenVLA or Isaac Sim.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ""):
    sys.path.insert(0, str(ROOT))

import numpy as np

from greenchallenge import layout
from tools import portfolio_graphics as graphics

LAB = Path("docs/control-room")
MEDIA = Path("assets/portfolio")
PRESETS = (
    ("v10", "1.0", False),
    ("v13", "1.3", False),
    ("v18-drop", "1.8", False),
    ("v18-keep", "1.8", True),
)


def record_runs() -> dict:
    captures = {}
    with TemporaryDirectory(prefix="gc-exhibit-") as tmp:
        for name, speed, keep in PRESETS:
            dest = Path(tmp) / f"{name}.json"
            cmd = [
                sys.executable, str(ROOT / "tools/smoke_test.py"), "--seconds", "3",
                "--speed", speed, "--capture", str(dest), "--telemetry", str(dest.with_suffix(".jsonl")),
            ]
            if keep:
                cmd.append("--keep-frozen")
            subprocess.run(cmd, cwd=ROOT, check=True)
            captures[name] = json.loads(dest.read_text(encoding="utf-8"))
    return captures


def patch_map() -> dict:
    # The numeric wire permutation is a reordering, not the finger calibration.
    return {
        "raw_names": [
            *layout.JOINT_NAMES_41, "body_roll", "body_pitch", "root_height", "root_yaw_global",
            *(f"base_{kind}_vel_{axis}" for kind in ("lin", "ang") for axis in "xyz"),
        ],
        "model_to_raw": layout.MODEL_TO_RAW_51.tolist(),
        "wire_to_raw": layout.raw_to_wire(np.arange(layout.RAW_STATE_DIM)).astype(int).tolist(),
        "delta_mask": layout.delta_mask().tolist(),
    }


def replay_js(captures: dict) -> bytes:
    def compact(value: object) -> str:
        return json.dumps(value, separators=(",", ":"), allow_nan=False)

    # Keep one request per line so the recorded values can be reviewed in Git.
    chunks = []
    for name, run in captures.items():
        metadata = {key: val for key, val in run.items() if key != "requests"}
        requests = ",\n      ".join(compact(row) for row in run["requests"])
        chunks.append(f'    "{name}": {compact(metadata)[:-1]},"requests":[\n      {requests}\n    ]}}')
    lines = ",\n".join(chunks)
    return (
        "// Generated by tools/build_portfolio.py from the CPU smoke test.\n"
        f'window.GC_REPLAY = {{\n  "patch": {compact(patch_map())},\n  "captures": {{\n{lines}\n  }}\n}};\n'
    ).encode("utf-8")


def offline_zip(path: Path, replay: bytes) -> None:
    files = {name: (ROOT / LAB / name).read_bytes() for name in ("index.html", "lab.css", "lab.js")}
    files["replay.js"] = replay
    with ZipFile(path, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for name, contents in files.items():
            entry = ZipInfo(f"green-control-room/{name}")
            entry.external_attr = 0o644 << 16
            archive.writestr(entry, contents, compress_type=ZIP_DEFLATED, compresslevel=9)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=ROOT,
                        help="write all generated files into this directory, preserving relative paths")
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/fonts/truetype/dejavu"))
    args = parser.parse_args()
    captures = record_runs()
    replay = replay_js(captures)
    lab, assets = args.output_root / LAB, args.output_root / MEDIA
    lab.mkdir(parents=True, exist_ok=True)
    assets.mkdir(parents=True, exist_ok=True)
    (lab / "replay.js").write_bytes(replay)
    offline_zip(assets / "control-room.zip", replay)
    graphics.render_exhibits(captures, assets, args.font_dir)


if __name__ == "__main__":
    main()
